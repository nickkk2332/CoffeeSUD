    static String error(final String name, final String args)
    {
        final int[] shape=commands.get(name);
        if(shape==null || args.contains("$g") || args.contains("$%")) return null;
        final int count=CMParms.parse(args).size();
        if(count<shape[0]) return name+" needs at least "+shape[0]+" arguments; got "+count;
        // A bare expression or free-form tail can contain spaces, so only enforce fixed forms here.
        if(shape[1]>=0 && count>shape[1]) return name+" takes "+shape[1]+" arguments; got "+count;
        return null;
    }
