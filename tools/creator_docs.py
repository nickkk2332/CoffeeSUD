#!/usr/bin/env python3
"""Build/check the creator handbook's source-derived reference snapshots.

This reads files only. --write updates documentation; --check verifies generated
content, all feature mappings and local Markdown links in the new guide set.
It does not launch the engine or claim that static coverage proves behavior.
"""
