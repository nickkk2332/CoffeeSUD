NOTICE = '<!-- Generated by tools/creator_docs.py; edit its sources, then --write. -->\n'


def read_help():
    """Read the shipped help's continued KEY=value format without eval."""
    entries = {}
    files = sorted((ROOT / 'CoffeeMud/resources/help').glob('*.ini'))
    # Prefer Archon entries where a topic has both player and author help.
    files.sort(key=lambda p: (p.name.startswith('arc_'), p.name))
    for path in files:
        lines = path.read_text(encoding='utf-8').splitlines()
        i = 0
        while i < len(lines):
            start = i + 1
            line = lines[i]
            i += 1
            while line.endswith('\\') and i < len(lines):
                line = line[:-1] + lines[i]
                i += 1
            if line.lstrip().startswith(('#', '!')):
                continue
            key, sep, value = line.partition('=')
            if sep and re.fullmatch(r'[A-Z0-9_]+', key.strip()):
                entries[key.strip()] = (value, path.relative_to(ROOT).as_posix(), start)
    return entries


def link(path, label=None):
    return '[' + (label or Path(path).name) + '](../../' + path + ')'


def generate(rows):
    out = {}
    statuses = [r['followup_status'] for r in rows]
    intro = ['# Reviewed feature index', '', NOTICE,
             '[Handbook](README.md) · [Tool reference](tool-reference.md)', '',
             'This maps every reviewed addition to a teaching chapter and implementation/',
             'regression evidence. Current `followup_status` takes precedence over historical',
             'baseline statuses in the inventory. Titles retain their review IDs; they are',
             'lookup labels, not expanded promises about every edge case.', '',
             f'**{len(rows)} entries: {statuses.count("implemented")} implemented, '
             f'{statuses.count("partial")} partial, {statuses.count("deferred")} deferred.**', '',
             '| Family | Chapter | Entries |', '| --- | --- | --- |']
    for theme, (name, chapter) in CHAPTERS.items():
        intro.append(f'| [{theme}: {name}](#{theme.lower()}) | [{name}]({chapter}) | '
                     f'{sum(r["theme"] == theme for r in rows)} |')
    intro += ['', '## Deferred work', '',
              'These are planned, not current authoring APIs. Existing primitives in the',
              'same area remain available. See also [LATER.md](../../LATER.md).', '']
    for r in rows:
        if r['followup_status'] == 'deferred':
            intro.append(f'- [{r["id"]}: {r["title"]}](#{r["id"].lower()})')
    intro += ['', 'JS2 remains partial: interpreted instruction budgets and bounded JSON background',
              'jobs work; unsafe forced preemption of synchronous native/compiled Java does not.',
              'The executions design draft is separate and not implemented.', '']
    coverage = io.StringIO(newline='')
    writer = csv.writer(coverage, lineterminator='\n')
    writer.writerow(['id', 'status', 'chapter', 'reference', 'sources', 'fixtures'])
    for theme, (name, chapter) in CHAPTERS.items():
        intro += [f'<a id="{theme.lower()}"></a>', '', f'## {theme}: {name}', '',
                  f'Teaching chapter: [{name}]({chapter}).', '']
        for r in rows:
            if r['theme'] != theme:
                continue
            rid = r['id']
            intro += [f'<a id="{rid.lower()}"></a>', '', f'### {rid}: {r["title"]}', '',
                      f'**{r["followup_status"]}** · [Guide]({chapter})', '']
            if r['followup_note']:
                intro += ['Current note: ' + r['followup_note'], '']
            if r['followup_status'] == 'partial':
                intro += ['Native calls cannot be safely force-stopped on the game thread. Use',
                          'interpreted budgets or JSON background jobs with explicit I/O timeouts.', '']
            sources = r['source_references'].split(';') if r['source_references'] else []
            fixtures = r['fixtures'].split(';') if r['fixtures'] else []
            if sources:
                intro += ['Implementation: ' + ' · '.join(link(s) for s in sources) + '.', '']
            if fixtures:
                intro += ['Examples/regressions: ' + ' · '.join(link(s) for s in fixtures) + '.', '']
            if not sources and r['followup_status'] != 'deferred':
                raise ValueError(f'{rid}: active entry without implementation reference')
            for path in sources + fixtures:
                if not (ROOT / path).exists():
                    raise ValueError(f'{rid}: missing inventory path {path}')
            writer.writerow([rid, r['followup_status'], chapter,
                             'feature-index.md#' + rid.lower(), r['source_references'], r['fixtures']])
    out['feature-index.md'] = '\n'.join(intro).rstrip() + '\n'
    out['coverage.csv'] = coverage.getvalue()

    entries = read_help()
    selected = set('BUILDING CREATE MODIFY GMODIFY CATALOG SAVE RESTORE SAVES PROFILE PARTY SWITCH AS '
                   'WINDOWS PAUSE RESUME TIMEMODE JS JRUN JCONSOLE SCRIPTABLE BEHAVIOR_SCRIPTABLE '
                   'GENABILITY GENLANGUAGE GENRACE GENCHARCLASS GENCRAFTSKILL GENGATHERSKILL GENWRIGHTSKILL '
                   'GENPOISON GENDISEASE GENTRAP GENTWEAKABILITY GENBEHAVIOR GENCOMMAND '
                   'ORIGINS CREATIONSTEPS CREATIONTEMPLATES STARTINGKITS TESTCHAR KIT PERKS TRAITS '
                   'CRAFTQUALITY RECIPEKEYS KNOWNRECIPES MUDCHAT ENCOUNTERS RANKS '
                   'QUESTS QUESTINFO QUESTCHECK QUESTMAKER ITEMSETS WORLD MODULES WORLD_MODULES COMPOSE WORLD_COMPOSITIONS COMBATRESULT WORLD_COMBAT ITEMMODS MODCRAFT WORLD_ITEMMODS MATERIALS RESOURCES '
                   'LANGUAGE VOCAB SOCIAL HELP AHELP COMPONENTS'.split())
    commands = {}
    source_paths = sorted({p for r in rows for p in r['source_references'].split(';') if p} |
                          {'CoffeeMud/com/planet_ink/coffee_mud/Commands/Modules.java',
                           'CoffeeMud/com/planet_ink/coffee_mud/Commands/CombatResult.java',
                           'CoffeeMud/com/planet_ink/coffee_mud/Commands/ItemMods.java',
                           'CoffeeMud/com/planet_ink/coffee_mud/Commands/ModCraft.java',
                           'CoffeeMud/com/planet_ink/coffee_mud/Abilities/Properties/Prop_ItemModifiers.java'})
    for path in source_paths:
        p = ROOT / path
        name = p.stem.upper()
        if '/Abilities/' in path:
            selected.add(name)
        if '/Behaviors/' in path:
            selected.add('BEHAVIOR_' + name)
        if '/Commands/' in path:
            source = p.read_text(encoding='utf-8')
            m = re.search(r'\baccess\s*=\s*I\s*\(\s*new\s+String\s*\[\s*\]\s*\{([^}]+)\}', source)
            words = re.findall(r'"([^"\n]+)"', m.group(1)) if m else []
            selected.update(word.replace(' ', '_') for word in words)
            # This excerpt is explicitly a source inspection aid, not a permission inference.
            sec = re.search(r'public boolean securityCheck\([^)]*\)\s*\{', source)
            if sec:
                start = sec.end()
                depth, end = 1, start
                while end < len(source) and depth:
                    depth += (source[end] == '{') - (source[end] == '}')
                    end += 1
                gate = ' '.join(source[start:end - 1].split())
            else:
                gate = 'Inherited; inspect execute() for operation-specific checks.'
            commands[path] = (words, gate)
    for r in rows:
        for path in r['fixtures'].split(';'):
            p = ROOT / path
            if p.is_file() and p.suffix == '.js':
                selected.update(re.findall(r'getHelpText\("([A-Z0-9_]+)"', p.read_text(encoding='utf-8')))
    # Include all world-added property/behavior help. This also catches help whose
    # defining source was absent from the earlier inventory's narrow source list.
    for key, (value, _, _) in entries.items():
        if key.startswith(('PROP_', 'BEHAVIOR_')) and 'CoffeeSUD' in value:
            selected.add(key)
    selected &= entries.keys()
    ref = ['# Creator tool and property reference', '', NOTICE,
           '[Handbook](README.md) · [Command gates](tool-permissions.md) · [World settings](world-settings.md)', '',
           'Snapshot of shipped help for authoring commands, generic definitions and the',
           'reviewed property/behavior families. It includes inherited tools these workflows',
           'depend on. Runtime AHELP may append schemas; world-owned help can override this',
           'stock text. Example names and room IDs require corresponding world content.', '',
           'Use the chapter guides for workflows and current limitations. This reference',
           'preserves help wording and uses the stock files rather than world overrides.',
           'Runtime schemas can add detail to property help. Legacy mentions of',
           'CoffeeMud or server administration do not reintroduce removed network services.', '',
           '## Topic index', '']
    for key in sorted(selected):
        ref.append(f'- [{key}](#{key.lower().replace("_", "-")})')
    for key in sorted(selected):
        value, path, line = entries[key]
        ref += ['', '<a id="' + key.lower().replace('_', '-') + '"></a>', '',
                f'## {key}', '', 'Source: ' + link(path, Path(path).name) + f', line {line}.', '']
        if value.strip() in entries:
            alias = value.strip()
            ref += [f'Help alias for **{alias}**.', '']
            value = entries[alias][0]
        value = value.replace('\\n', '\n').replace('\\r', '').replace('\\t', '    ')
        value = re.sub(r'\^[a-zA-Z?]', '', value)
        # Preserve help as text, including examples, tags and backslashes.
        ref += ['```text']
        for line in value.splitlines():
            ref.extend(textwrap.wrap(line, width=92, replace_whitespace=False,
                                     drop_whitespace=False, break_long_words=False,
                                     break_on_hyphens=False) or [''])
        ref += ['```']
    out['tool-reference.md'] = '\n'.join(line.rstrip() for line in ref).rstrip() + '\n'
    gates = ['# Command entry points and gates', '', NOTICE,
             '[Handbook](README.md) · [Tool reference](tool-reference.md)', '',
             'Source audit of command classes linked by the original feature inventory and',
             'newer handbook chapters. Aliases are',
             'the literal access words declared by each class. The source link is authoritative',
             'when words are constructed dynamically. The securityCheck body below is a code',
             'excerpt, not a claim that every subcommand has identical permissions: execute()',
             'can impose further builder/DEV, filesystem, target and operation restrictions.',
             'Player-facing tools may intentionally have a broad entry gate.', '']
    for path, (words, gate) in commands.items():
        gates += ['## ' + ', '.join(words or [Path(path).stem]), '', link(path), '',
                  '```java', gate, '```', '']
    out['tool-permissions.md'] = '\n'.join(gates).rstrip() + '\n'

    settings_path = 'CoffeeMud/com/planet_ink/coffee_mud/core/save/WorldSettings.java'
    source = (ROOT / settings_path).read_text(encoding='utf-8')
    keyblock = source.split('KEYS\t=')[1].split('};')[0]
    prefixblock = source.split('PREFIXES\t=')[1].split('};')[0]
    keys = re.findall(r'"([A-Z0-9_]+)"', keyblock)
    prefixes = re.findall(r'"([A-Z0-9_]+)"', prefixblock)
    settings = ['# World settings reference', '', NOTICE, '[Handbook](README.md)', '',
                'Only these keys and prefixed families are accepted from `world/world.ini`.',
                'Unknown keys are reported and ignored. Engine-only settings such as database,',
                'logs and JavaScript approval/runtime limits belong in `coffeemud.ini` or launch',
                'overrides. Inclusion in the allowlist does not imply a default value.', '',
                '**Precedence:** engine INI, then world.ini, then launch overrides.',
                '`WORLD` / `LIST WORLDINI` shows effective values and provenance.',
                '`WORLD SET KEY=value` writes the file in builder mode; it takes effect on',
                'the next startup. A blank value removes an override.', '',
                'Source: ' + link(settings_path) + '. For value grammar and shipped defaults,',
                'read the comments in [coffeemud.ini](../../CoffeeMud/coffeemud.ini), the',
                '[tool reference](tool-reference.md), and the relevant system chapter.', '',
                '## Exact keys', '']
    settings += ['- `' + key + '`' for key in keys]
    settings += ['', '## Prefix families', '',
                 'A prefix needs a nonempty suffix; the consuming subsystem defines its grammar.', '']
    settings += ['- `' + prefix + '*`' for prefix in prefixes]
    settings += ['', '## Common starting policies', '', '```ini',
                 'START=New Area#0', 'TIMEMODE=TURNS', 'PARTYMAX=4', 'ACTIVECHARMAX=4',
                 'PROFILEMAX=8', 'PARTYSUMMON=MEET', '```', '',
                 'Replace the start ID with a real room. Zero size limits mean unlimited.',
                 'World-enforced restrictions cannot be relaxed by player convenience settings.',
                 'Keep an ordinary NEW-game test: builder privileges can hide policy mistakes.', '']
    out['world-settings.md'] = '\n'.join(settings)
    return out, len(selected), len(commands)


@lru_cache(maxsize=None)
def anchors(path):
    text = path.read_text(encoding='utf-8')
    found = set(re.findall(r'<a\s+(?:id|name)=["\']([^"\']+)', text))
    if path.suffix == '.md':
        seen = {}
        # Code fences do not define Markdown headings/anchors.
        clean = re.sub(r'^```[^\n]*\n.*?^```[^\n]*$', '', text, flags=re.M | re.S)
        for heading in re.findall(r'^#{1,6}\s+(.+)$', clean, re.M):
            slug = re.sub(r'[^\w\- ]', '', heading.lower()).replace(' ', '-')
            n = seen.get(slug, 0)
            seen[slug] = n + 1
            found.add(slug if n == 0 else slug + '-' + str(n))
    return found


def check_links():
    errors = []
    files = list(DOC.rglob('*.md')) + [ROOT / 'audit/developer-tools-audit.md',
                                    ROOT / 'README.md', ROOT / 'audit/README.md']
    files += [ROOT / 'SUDDocs' / (name + '.md') for name in
              ('authoring-reliability', 'languages', 'organizations',
               'party-rules', 'presentation', 'travel')]
    for path in files:
        if not path.exists():
            errors.append(f'missing guide/audit {path.relative_to(ROOT)}')
            continue
        text = path.read_text(encoding='utf-8')
        clean = re.sub(r'^```[^\n]*\n.*?^```[^\n]*$', '', text, flags=re.M | re.S)
        for raw in re.findall(r'\[[^\]\n]*\]\(([^)]+)\)', clean):
            url = raw.strip().strip('<>')
            if re.match(r'^[a-zA-Z]+:', url):
                continue
            target, _, fragment = unquote(url).partition('#')
            p = (path.parent / target).resolve() if target else path
            if not p.exists():
                errors.append(f'{path.relative_to(ROOT)}: missing link {url}')
            elif fragment and p.suffix in ('.md', '.html') and fragment not in anchors(p):
                errors.append(f'{path.relative_to(ROOT)}: missing anchor {url}')
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = list(csv.DictReader((ROOT / 'audit/project-feature-status.csv').open(newline='')))
    if len({r['id'] for r in rows}) != len(rows):
        raise ValueError('duplicate feature IDs')
    if set(r['theme'] for r in rows) != set(CHAPTERS):
        raise ValueError('feature themes need chapter mapping updates')
    generated, topics, commands = generate(rows)
    errors = []
    for name, text in generated.items():
        path = DOC / name
        if args.write:
            path.write_text(text, encoding='utf-8')
        elif not path.exists() or path.read_text(encoding='utf-8') != text:
            errors.append('stale reference: ' + str(path.relative_to(ROOT)))
    if args.check:
        errors.extend(check_links())
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    print(f'{"Wrote" if args.write else "Checked"} {len(generated)} references; '
          f'{len(rows)} feature mappings, {topics} help topics, {commands} command gates.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
